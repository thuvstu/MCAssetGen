function spiderLegs(): PartDef[] {
  const zs = [-9.2, -7.1, -5, -2.9];
  const yawR = [-52, -18, 18, 50];
  const yawL = [52, 18, -18, -50];
  const legs: PartDef[] = [];
  zs.forEach((z, i) => {
    legs.push(
      box({
        id: `legR${i + 1}`,
        name: `右脚${i + 1}`,
        o: [-18, 7.2, z - 0.7],
        s: [14, 1.5, 1.5],
        p: [-4, 8, z],
        r: [0, yawR[i], 34],
        slot: "secondary",
        group: "leg",
        anim: "swing",
        axis: "z",
        amp: 0.2,
        phase: i % 2 ? Math.PI : 0,
      }),
      box({
        id: `legL${i + 1}`,
        name: `左脚${i + 1}`,
        o: [4, 7.2, z - 0.7],
        s: [14, 1.5, 1.5],
        p: [4, 8, z],
        r: [0, yawL[i], -34],
        slot: "secondary",
        group: "leg",
        anim: "swing",
        axis: "z",
        amp: 0.2,
        phase: i % 2 ? 0 : Math.PI,
      }),
    );
  });
  return legs;
}

const legScale = (v: Vec3): Record<string, Vec3> => {
  const o: Record<string, Vec3> = {};
  for (let i = 1; i <= 4; i++) {
    o[`legR${i}`] = v;
    o[`legL${i}`] = v;
  }
  return o;
};

