function box(p: {
  id: string;
  name: string;
  o: Vec3;
  s: Vec3;
  p?: Vec3;
  r?: Vec3;
  slot?: ColorSlot;
  anim?: PartDef["anim"];
  phase?: number;
  axis?: Axis;
  amp?: number;
  optional?: boolean;
  on?: boolean;
  opacity?: number;
  group?: PartDef["group"];
  attach?: string;
}): PartDef {
  const pivot = p.p ?? [p.o[0] + p.s[0] / 2, p.o[1] + p.s[1] / 2, p.o[2] + p.s[2] / 2];
  return {
    id: p.id,
    name: p.name,
    optional: p.optional ?? false,
    defaultOn: p.on ?? !(p.optional ?? false),
    origin: p.o,
    size: p.s,
    pivot,
    rotation: p.r ?? [0, 0, 0],
    slot: p.slot ?? "primary",
    anim: p.anim ?? "none",
    phase: p.phase ?? 0,
    axis: p.axis ?? "x",
    amp: p.amp ?? 0.55,
    opacity: p.opacity ?? 1,
    group: p.group ?? "body",
    attach: p.attach,
  };
}

